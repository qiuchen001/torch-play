print("   └─────────────┘    └──────────────┘    └─────────────┘")

print("\n3. 训练流程:")
print("   ┌─────────────┐    ┌──────────────┐    ┌─────────────┐")
print("   │ 输入序列    │ -> │ 模型预测     │ -> │ 计算损失    │")
print("   │ 'hel'      │    │ 概率分布     │    │ 预测vs真实  │")
print("   └─────────────┘    └──────────────┘    └─────────────┘")
print("                              ↓")
print("   ┌─────────────┐    ┌──────────────┐    ┌─────────────┐")
print("   │ 反向传播    │ <- │ 梯度计算     │ <- │ 参数更新    │")
print("   │ 更新参数    │    │ 优化器       │    │ 更准确预测  │")
print("   └─────────────┘    └──────────────┘    └─────────────┘")

print("\n4. 生成流程:")
print("   ┌─────────────┐    ┌──────────────┐    ┌─────────────┐")
print("   │ 起始文本    │ -> │ 模型预测     │ -> │ 采样选择    │")
print("   │ 'hel'      │    │ 概率分布     │    │ 下一个字符  │")
print("   └─────────────┘    └──────────────┘    └─────────────┘")
print("                              ↓")
print("   ┌─────────────┐    ┌──────────────┐    ┌─────────────┐")
print("   │ 更新序列    │ <- │ 添加字符     │ <- │ 重复生成    │")
print("   │ 'ell'      │    │ 'l'          │    │ 直到完成    │")
print("   └─────────────┘    └──────────────┘    └─────────────┘")

print("\n=== 关键设计原理 ===")
print("• 数据流: 文本 → 序列 → 向量 → 预测 → 生成")
print("• 记忆机制: LSTM记住前面的字符信息")
print("• 概率采样: 根据概率分布选择下一个字符")
print("• 滑动窗口: 保持固定长度的上下文")
print("• 端到端: 从原始文本到生成文本的完整流程")
