print("=== 文本生成系统架构图 ===\n")

print("┌─────────────────────────────────────────────────────────────┐")
print("│                    文本生成系统架构                          │")
print("└─────────────────────────────────────────────────────────────┘\n")

print("1. 数据准备阶段:")
print("   ┌─────────────┐    ┌──────────────┐    ┌─────────────┐")
