print("   │ 'hello'    │    │ h→0, e→1...  │    │ (hel,l)     │")
print("   └─────────────┘    └──────────────┘    └─────────────┘")

print("\n2. 模型架构:")
print("   ┌─────────────┐    ┌──────────────┐    ┌─────────────┐")
print("   │ 嵌入层      │ -> │ LSTM层       │ -> │ 输出层      │")
